"""Populate the knowledge base with comparative analysis documents from benchmark cases.

These documents are **evaluation material**, not research sources: they are
generated from the benchmark set's own ground-truth answers and expected winners.
They stay in the repository for benchmark reproduction, and they are kept out of
the default research basis by their provenance — see `setup.py` and
`src/deepchoice/retrievers/chroma_kb.py`. That separation is by explicit
provenance, not by deleting the files or by stripping their answer text.
"""
import json
import os
from pathlib import Path

KB_DIR = Path(__file__).parent
DATA_DIR = KB_DIR / "data"
BENCHMARK_CASES = KB_DIR.parent / "benchmarks" / "cases_200.json"

# A dedicated directory, so a generated answer document is identifiable by where
# it lives as well as by the marker it carries. Never merged into `blogs/`.
OUT_DIR = DATA_DIR / "benchmark_answers"

# The marker `setup.py` reads to record provenance in the index. It describes
# where the text came from, and is not used to decide whether a document is any
# good.
PROVENANCE_LINE = ("**Provenance**: benchmark ground-truth answer, generated by "
                   "chroma_kb/populate_benchmark_kb.py from benchmarks/cases_200.json; "
                   "evaluation material, not a research source.")


def generate_docs():
    cases = json.loads(BENCHMARK_CASES.read_text(encoding="utf-8"))
    base_cases = {}
    for c in cases:
        cid = c["id"]
        if "-v" in cid:
            continue
        tech_key = f"{c.get('tech_a', '')} vs {c.get('tech_b', '')}"
        if tech_key not in base_cases:
            base_cases[tech_key] = c

    os.makedirs(OUT_DIR, exist_ok=True)
    count = 0
    for tech_key, case in base_cases.items():
        notes = case.get("ground_truth_notes", "")
        contradictions = case.get("known_contradictions", [])
        if not notes and not contradictions:
            continue
        lines = [f"# {tech_key}", "", PROVENANCE_LINE, "",
                 f"**Category**: {case.get('category', '')}",
                 f"**Expected winner**: {case.get('expected_winner', 'context-dependent')}",
                 "", "## Analysis", "", notes, ""]
        if contradictions:
            lines.append("## Known Contradictions")
            lines.append("")
            for kc in contradictions:
                lines.append(f"### {kc.get('topic', '')}")
                lines.append(f"- Position A: {kc.get('position_a', '')}")
                lines.append(f"- Position B: {kc.get('position_b', '')}")
                lines.append("")
        filename = tech_key.replace(" ", "-").replace("/", "-").lower()[:80] + ".md"
        (OUT_DIR / filename).write_text("\n".join(lines), encoding="utf-8")
        count += 1
    print(f"Generated {count} documents in {OUT_DIR}")
    return count

if __name__ == "__main__":
    generate_docs()
    print("Done. Run setup.py to ingest.")
