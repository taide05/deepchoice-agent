_EXPLICIT_HOST_ALIASES = {"www.sqlite.org": "sqlite.org"}
_HOST_LABEL_RE = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$")


def _normalize_hostname(hostname: str) -> str | None:
    """Return a strict lower-case IDNA hostname, or None for invalid input."""
    if not isinstance(hostname, str) or not hostname or any(ord(ch) < 32 or 127 <= ord(ch) <= 159 for ch in hostname):
        return None
    hostname = hostname.casefold()
    if hostname.endswith("."):
        hostname = hostname[:-1]
    if not hostname or any(ch in hostname for ch in ("\\", "/", "@", " ")):
        return None
    try:
        ascii_host = hostname.encode("idna").decode("ascii").casefold()
    except UnicodeError:
        return None
    if len(ascii_host) > 253:
        return None
    labels = ascii_host.split(".")
    if not labels or any(not _HOST_LABEL_RE.fullmatch(label) for label in labels):
        return None
    return ascii_host


def _parse_http_host(url: str) -> tuple[str, str] | None:
    """Parse a syntactically valid HTTP(S) host without inferring path scope."""
    if not isinstance(url, str) or not url or any(ord(ch) < 32 or 127 <= ord(ch) <= 159 for ch in url) or "\\" in url:
        return None
    try:
        parsed = urlsplit(url)
        if parsed.scheme.casefold() not in {"http", "https"}:
            return None
        if parsed.username is not None or parsed.password is not None:
            return None
        port = parsed.port
    except (ValueError, UnicodeError):
        return None
    if port is not None and port not in {80, 443}:
        return None
    host = _normalize_hostname(parsed.hostname)
    if host is None:
        return None
    return host, parsed.path or ""


def parse_http_identity(url: str) -> tuple[str, tuple[str, ...]] | None:
    """Add conservative path-scope parsing for a curated locator match."""
    parsed = _parse_http_host(url)
    if parsed is None:
        return None
    host, path = parsed
    # Conservative scope: do not resolve any percent-encoded path syntax.
    if "%" in path:
        return None
    pieces = path.split("/")
    if any(piece in {".", ".."} for piece in pieces):
        return None
    if any(piece == "" for piece in pieces[1:-1]):
        return None
    return host, tuple(piece for piece in pieces if piece)


def normalized_hostname(url: str) -> str | None:
    """Return a valid HTTP(S) hostname for source-family classification."""
    parsed = _parse_http_host(url)
    return parsed[0] if parsed else None


def is_catalog_official_url(url: str) -> bool:
    """Match an HTTP(S) URL against exact catalog hosts and seed path prefixes."""
    parsed = parse_http_identity(url)
    if parsed is None:
        return False
    host, path = parsed
    host = _EXPLICIT_HOST_ALIASES.get(host, host)
    for entry in TECH_DOCS.values():
        seed = parse_http_identity(entry.get("url", ""))
        if seed is None or seed[0] != host:
            continue
        seed_path = seed[1]
        if not seed_path or path[: len(seed_path)] == seed_path:
            return True
    return False


